"""Measure the low-frequency panel lighting from the reference screenshots and emit
Source/UI/PanelLighting.h: a coarse RGB grid per skin that the UI interpolates and
then overlays with procedural brushed-metal streaks.

Controls are masked out and the holes are filled by harmonic (neighbour-average)
inpainting at grid resolution.

usage: python tools/gen_lighting.py
"""
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, "reference")
OUT = os.path.join(ROOT, "Source", "UI", "PanelLighting.h")

CELL = 32
PANEL = (0, 96, 2396, 688)  # x0, y0, x1, y1 of the brushed panel interior (reference px)
TOP_ROWS = (56, 96)         # top bevel rows, emitted as exact 1D profiles
BOTTOM_ROWS = (688, 865)    # bottom bevel + bottom bar rows
# columns free of controls, used for the row profiles
PROFILE_COLS = [(400, 640), (1030, 1250), (1620, 1740), (1960, 2040), (2250, 2390)]
PROFILE_COLS_BLUEY = [(400, 640), (1030, 1250), (2250, 2390)]
PROFILE_COLS_SECTION = [(1620, 1740), (1960, 2040)]

# Regions occupied by controls / artwork (x0, y0, x1, y1).
MASKS = [
    (80, 200, 490, 640),     # input knob + labels
    (545, 200, 960, 640),    # output knob + labels
    (1030, 125, 1245, 705),  # attack / release
    (1340, 125, 1485, 625),  # ratio
    (1780, 115, 1890, 215),  # lamp
    (1555, 215, 2115, 570),  # VU meter
    (1690, 595, 1975, 695),  # CLA-76 logo
    (2165, 125, 2396, 625),  # meter buttons
]
BLUE_SECTION = (1523, 96, 2136, 688)  # Bluey only (plate between the seams)


MASK_PAD = 40  # also exclude the soft drop shadows around controls


def grid_for(img, rect, masks):
    x0, y0, x1, y1 = rect
    gw, gh = (x1 - x0 + CELL - 1) // CELL, (y1 - y0 + CELL - 1) // CELL
    valid = np.ones((img.shape[0], img.shape[1]), bool)
    for mx0, my0, mx1, my1 in masks:
        valid[max(0, my0 - MASK_PAD):my1 + MASK_PAD, max(0, mx0 - MASK_PAD):mx1 + MASK_PAD] = False
    g = np.zeros((gh, gw, 3))
    known = np.zeros((gh, gw), bool)
    for j in range(gh):
        for i in range(gw):
            cx0, cy0 = x0 + i * CELL, y0 + j * CELL
            cx1, cy1 = min(cx0 + CELL, x1), min(cy0 + CELL, y1)
            v = valid[cy0:cy1, cx0:cx1]
            if v.sum() > (cx1 - cx0) * (cy1 - cy0) * 0.4:
                g[j, i] = np.median(img[cy0:cy1, cx0:cx1][v], axis=0)
                known[j, i] = True
    # harmonic fill of unknown cells
    if known.any():
        g[~known] = g[known].mean(axis=0)
        for _ in range(400):
            p = np.pad(g, ((1, 1), (1, 1), (0, 0)), mode="edge")
            avg = (p[:-2, 1:-1] + p[2:, 1:-1] + p[1:-1, :-2] + p[1:-1, 2:]) / 4
            g[~known] = avg[~known]
    return g


def emit(name, rect, g):
    x0, y0, x1, y1 = rect
    gh, gw, _ = g.shape
    vals = ",".join(str(int(round(v))) for v in g.reshape(-1))
    return (f"    inline constexpr LightingGrid {name} {{ {x0}, {y0}, {x1}, {y1}, {CELL}, {gw}, {gh},\n"
            f"        {{ {vals} }} }};\n")


def profile(img, rows, cols):
    y0, y1 = rows
    sel = np.concatenate([img[y0:y1, c0:c1] for c0, c1 in cols], axis=1)
    return np.median(sel, axis=1)


def emit_profile(name, rows, prof):
    vals = ",".join(str(int(round(v))) for v in prof.reshape(-1))
    return (f"    inline constexpr RowProfile {name} {{ {rows[0]}, {rows[1]},\n"
            f"        {{ {vals} }} }};\n")


def main():
    load = lambda f: np.asarray(Image.open(os.path.join(REF, f)).convert("RGB")).astype(float)
    blacky = load("ui_blacky_2396.png")
    bluey = load("ui_bluey_aligned.png")  # ui_bluey_2396.png shifted up 4px to register with blacky

    parts = [
        emit("blackyPanel", PANEL, grid_for(blacky, PANEL, MASKS)),
        emit("blueyPanel", PANEL, grid_for(bluey, PANEL, MASKS + [BLUE_SECTION])),
        emit("blueySection", BLUE_SECTION, grid_for(bluey, BLUE_SECTION, MASKS)),
        emit_profile("blackyTop", TOP_ROWS, profile(blacky, TOP_ROWS, PROFILE_COLS)),
        emit_profile("blackyBottom", BOTTOM_ROWS, profile(blacky, BOTTOM_ROWS, PROFILE_COLS)),
        emit_profile("blueyTop", TOP_ROWS, profile(bluey, TOP_ROWS, PROFILE_COLS_BLUEY)),
        emit_profile("blueyBottom", BOTTOM_ROWS, profile(bluey, BOTTOM_ROWS, PROFILE_COLS_BLUEY)),
        emit_profile("sectionTop", TOP_ROWS, profile(bluey, TOP_ROWS, PROFILE_COLS_SECTION)),
        emit_profile("sectionBottom", BOTTOM_ROWS, profile(bluey, BOTTOM_ROWS, PROFILE_COLS_SECTION)),
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by tools/gen_lighting.py - do not edit.\n"
                "// Coarse RGB lighting fields measured from the reference shots (controls masked out).\n"
                "#pragma once\n\n#include <array>\n#include <cstdint>\n\n"
                "struct LightingGrid\n{\n    int x0, y0, x1, y1, cell, w, h;\n"
                "    std::array<std::uint8_t, 8192> rgb;\n};\n\n"
                "struct RowProfile\n{\n    int y0, y1;\n    std::array<std::uint8_t, 1024> rgb;\n};\n\n"
                "namespace Lighting\n{\n")
        f.write("".join(parts))
        f.write("}\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
